CREATE TABLE tb_usuario (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(20)  NOT NULL,
    nome    VARCHAR(120) NOT NULL,
    email   VARCHAR(160),
    cpf     VARCHAR(14),
    telefone VARCHAR(20),
    senha   VARCHAR(100) NOT NULL,
    perfil  VARCHAR(20)  NOT NULL,
    ativo   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuario_codigo UNIQUE (codigo),
    CONSTRAINT uk_usuario_email  UNIQUE (email),
    CONSTRAINT uk_usuario_cpf UNIQUE (cpf),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'GARCOM', 'COZINHA', 'CAIXA'))
);

CREATE TABLE tb_categoria (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(80) NOT NULL,
    ordem  INTEGER     NOT NULL DEFAULT 0,
    ativo  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE tb_produto (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id  BIGINT        NOT NULL REFERENCES tb_categoria (id),
    nome          VARCHAR(120)  NOT NULL,
    descricao     VARCHAR(500),
    preco         NUMERIC(10,2) NOT NULL,
    ativo         BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_produto_nome  UNIQUE (nome),
    CONSTRAINT ck_produto_preco CHECK (preco >= 0)
);
CREATE INDEX ix_produto_categoria ON tb_produto (categoria_id);

CREATE TABLE tb_ingrediente (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(80) NOT NULL,
    ativo  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_ingrediente_nome UNIQUE (nome)
);

CREATE TABLE tb_produto_ingrediente (
    produto_id      BIGINT NOT NULL REFERENCES tb_produto (id) ON DELETE CASCADE,
    ingrediente_id  BIGINT NOT NULL REFERENCES tb_ingrediente (id),
    PRIMARY KEY (produto_id, ingrediente_id)
);

CREATE TABLE tb_imagem_produto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id  BIGINT       NOT NULL REFERENCES tb_produto (id) ON DELETE CASCADE,
    caminho     VARCHAR(255) NOT NULL,
    principal   BOOLEAN      NOT NULL DEFAULT FALSE,
    ordem       INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX ix_imagem_produto ON tb_imagem_produto (produto_id);
CREATE UNIQUE INDEX uk_imagem_principal ON tb_imagem_produto (produto_id) WHERE principal;

CREATE TABLE tb_mesa (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                  INTEGER     NOT NULL,
    capacidade              INTEGER     NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'DISPONIVEL',
    ativo                   BOOLEAN     NOT NULL DEFAULT TRUE,
    pagamento_iniciado_por  BIGINT      REFERENCES tb_usuario (id),
    pagamento_iniciado_em   TIMESTAMP,
    version                 BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_mesa_numero      UNIQUE (numero),
    CONSTRAINT ck_mesa_numero      CHECK (numero > 0),
    CONSTRAINT ck_mesa_capacidade  CHECK (capacidade > 0),
    CONSTRAINT ck_mesa_status      CHECK (status IN ('DISPONIVEL', 'OCUPADA', 'RESERVADA', 'EM_PAGAMENTO')),
    CONSTRAINT ck_mesa_pagamento   CHECK (
        (status = 'EM_PAGAMENTO' AND pagamento_iniciado_por IS NOT NULL AND pagamento_iniciado_em IS NOT NULL)
        OR
        (status <> 'EM_PAGAMENTO' AND pagamento_iniciado_por IS NULL AND pagamento_iniciado_em IS NULL)
    )
);

CREATE TABLE tb_pedido (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa_id       BIGINT        NOT NULL REFERENCES tb_mesa (id),
    garcom_id     BIGINT        NOT NULL REFERENCES tb_usuario (id),
    status        VARCHAR(20)   NOT NULL DEFAULT 'AGUARDANDO',
    valor_total   NUMERIC(10,2) NOT NULL DEFAULT 0,
    data_criacao  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pedido_status CHECK (status IN ('AGUARDANDO', 'EM_PREPARO', 'PRONTO', 'PAGO', 'CANCELADO')),
    CONSTRAINT ck_pedido_valor  CHECK (valor_total >= 0)
);
CREATE INDEX ix_pedido_mesa ON tb_pedido (mesa_id);
CREATE INDEX ix_pedido_status_data ON tb_pedido (status, data_criacao);

CREATE TABLE tb_item_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT        NOT NULL REFERENCES tb_pedido (id) ON DELETE CASCADE,
    produto_id      BIGINT        NOT NULL REFERENCES tb_produto (id),
    quantidade      INTEGER       NOT NULL,
    preco_unitario  NUMERIC(10,2) NOT NULL,
    observacao      VARCHAR(255),
    status          VARCHAR(20)   NOT NULL DEFAULT 'AGUARDANDO',
    atualizado_em   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_preco      CHECK (preco_unitario >= 0),
    CONSTRAINT ck_item_status     CHECK (status IN ('AGUARDANDO', 'EM_PREPARO', 'PRONTO', 'CANCELADO'))
);
CREATE INDEX ix_item_pedido ON tb_item_pedido (pedido_id);
CREATE INDEX ix_item_status ON tb_item_pedido (status);

CREATE TABLE tb_transferencia_mesa (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT    NOT NULL REFERENCES tb_pedido (id),
    mesa_origem_id   BIGINT    NOT NULL REFERENCES tb_mesa (id),
    mesa_destino_id  BIGINT    NOT NULL REFERENCES tb_mesa (id),
    usuario_id       BIGINT    NOT NULL REFERENCES tb_usuario (id),
    data_hora        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_transferencia_mesas CHECK (mesa_origem_id <> mesa_destino_id)
);
CREATE INDEX ix_transferencia_pedido ON tb_transferencia_mesa (pedido_id);

CREATE TABLE tb_caixa (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operador_id           BIGINT        NOT NULL REFERENCES tb_usuario (id),
    turno                 VARCHAR(20),
    status                VARCHAR(20)   NOT NULL DEFAULT 'ABERTO',
    valor_abertura        NUMERIC(10,2) NOT NULL,
    aberto_em             TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valor_fechamento      NUMERIC(10,2),
    valor_esperado        NUMERIC(10,2),
    fechado_em            TIMESTAMP,
    CONSTRAINT ck_caixa_status   CHECK (status IN ('ABERTO', 'FECHADO')),
    CONSTRAINT ck_caixa_abertura CHECK (valor_abertura >= 0),
    CONSTRAINT ck_caixa_fechado  CHECK ((status = 'FECHADO') = (fechado_em IS NOT NULL))
);
CREATE UNIQUE INDEX uk_caixa_unico_aberto ON tb_caixa (status) WHERE status = 'ABERTO';

CREATE TABLE tb_movimentacao_caixa (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caixa_id    BIGINT        NOT NULL REFERENCES tb_caixa (id),
    usuario_id  BIGINT        NOT NULL REFERENCES tb_usuario (id),
    tipo        VARCHAR(20)   NOT NULL,
    valor       NUMERIC(10,2) NOT NULL,
    motivo      VARCHAR(255),
    data_hora   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_movimentacao_tipo  CHECK (tipo IN ('SANGRIA', 'REFORCO')),
    CONSTRAINT ck_movimentacao_valor CHECK (valor > 0)
);
CREATE INDEX ix_movimentacao_caixa ON tb_movimentacao_caixa (caixa_id);

CREATE TABLE tb_pagamento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT        NOT NULL REFERENCES tb_pedido (id),
    caixa_id         BIGINT        REFERENCES tb_caixa (id),
    forma_pagamento  VARCHAR(20)   NOT NULL,
    valor            NUMERIC(10,2) NOT NULL,
    troco            NUMERIC(10,2) NOT NULL DEFAULT 0,
    data_pagamento   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pagamento_forma CHECK (forma_pagamento IN ('DINHEIRO', 'CREDITO', 'DEBITO', 'PIX', 'VALE')),
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0),
    CONSTRAINT ck_pagamento_troco CHECK (troco >= 0)
);
CREATE INDEX ix_pagamento_pedido ON tb_pagamento (pedido_id);
CREATE INDEX ix_pagamento_caixa  ON tb_pagamento (caixa_id);

CREATE TABLE tb_configuracao (
    id                          BIGINT       PRIMARY KEY DEFAULT 1,
    nome_restaurante            VARCHAR(120) NOT NULL DEFAULT 'RestManager',
    taxa_servico_percentual     NUMERIC(5,2) NOT NULL DEFAULT 10.00,
    imprimir_comanda_ao_aceitar BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_configuracao_unica CHECK (id = 1),
    CONSTRAINT ck_configuracao_taxa  CHECK (taxa_servico_percentual BETWEEN 0 AND 100)
);
